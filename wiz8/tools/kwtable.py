"""Keyword tables for the hook:  python tools/kwtable.py  ->  hook/kw_table.h  (then rebuild ddraw.dll)

The game matches what the player asks against the English keywords of the NPC script. The hook lets the
player ask with the Japanese term instead (topic list, clicked words in the log):

  g_kw_j2e[]  Japanese term -> English keywords to try, "/"-separated, most likely first
  g_kw_e2j[]  English topic (upper case) -> the Japanese term shown in the topic list

Sources: every "term(KEYWORD)" the build writes into the dialogue (keywords.annotate), the keyword table
(work/kw67), NPC names (NPC.DBS), place names (LEVELS.DBS without the floor number) and the two topics a
new game starts with (STRINGDATA#2023/#2024).

  g_npc_name[] Japanese NPC name -> English NPC.DBS name, for the level triggers named "_<NPC name>"
"""
import collections, glob, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import keywords
from jptext import KW_MARK

ROOT = keywords.ROOT
W = keywords.W
OUT = os.path.join(ROOT, 'hook', 'kw_table.h')
SPAN = re.compile(KW_MARK + r'([^(' + KW_MARK + r']+)\(([^)]+)\)')
JP = re.compile(r'[^\x00-\x7f]')


def load_ja():
    ja = {}
    for f in glob.glob(os.path.join(W, 'ja', '*.json')):
        d = json.load(open(f, encoding='utf-8'))
        if isinstance(d, dict):
            ja.update({k: v for k, v in d.items() if isinstance(v, str)})
    return ja


def build():
    ja = load_ja()
    use = collections.Counter()      # (KEYWORD, term) -> how often the dialogue shows this pair
    for lid, en, t in keywords.nsf_lines():
        for term, kw in SPAN.findall(keywords.annotate(lid, en, t)):
            use[(kw.upper(), term.strip())] += 1
    j2e = collections.defaultdict(collections.Counter)
    e2j = {}
    for (kw, term), n in use.items():
        j2e[term][kw] += n
    for kw, terms in keywords.load_table().items():
        for t in terms:
            if t.upper() != kw and JP.search(t):
                j2e[t][kw] += 0
    # topic-list spelling: the term the dialogue uses most for this keyword
    best = {}
    for (kw, term), n in use.items():
        if n > best.get(kw, (0, ''))[0]:
            best[kw] = (n, term)
    for kw, (n, term) in best.items():
        e2j[kw] = term
    for kw, terms in keywords.load_table().items():
        if kw not in e2j and terms and terms[0].upper() != kw and JP.search(terms[0]):
            e2j[kw] = terms[0]

    def name_pair(en_name, ja_name):
        en_name, ja_name = en_name.strip(), (ja_name or '').strip()
        if len(en_name) < 2 or not JP.search(ja_name) or JP.search(en_name):
            return
        kw = en_name.upper()
        j2e[ja_name][kw] += 0
        e2j.setdefault(kw, ja_name)

    for x in json.load(open(os.path.join(W, 'text', 'dbs_npc.json'), encoding='utf-8')):
        if x.get('ctx') == 'NPC name':
            name_pair(x['en'], ja.get(x['id']))
    for x in json.load(open(os.path.join(W, 'text', 'dbs_levels.json'), encoding='utf-8')):
        t = ja.get(x['id']) or ''
        name_pair(re.sub(r'\s*\d+$', '', x['en']), re.sub(r'\s*\d+$', '', t))
    for sid in ('STRINGDATA#2023', 'STRINGDATA#2024'):
        en = {y['id']: y['en'] for y in json.load(open(os.path.join(W, 'text', 'stringdata.json'), encoding='utf-8'))}
        name_pair(en[sid], ja.get(sid))
    # the yes/no buttons put their (translated) label into the input; NPC scripts answer to YES / NO
    for sid, kws in (('STRINGDATA#2015', ['YES', 'YEAH', 'YEP', 'SURE']), ('STRINGDATA#2016', ['NO', 'NOPE', 'NEVER']),
                     ('STRINGDATA#205', ['YES', 'YEAH', 'YEP', 'SURE']), ('STRINGDATA#206', ['NO', 'NOPE', 'NEVER'])):
        t = (ja.get(sid) or '').strip()
        if t and JP.search(t):
            for i, k in enumerate(kws):
                j2e[t][k] += 1000 - i
    # every topic-list term must lead back to its keyword
    for kw, term in e2j.items():
        j2e[term][kw] += 0
    return ({t: [k for k, _ in sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))] for t, c in j2e.items()}, e2j)


def npc_names():
    ja = load_ja()
    out = set()
    for x in json.load(open(os.path.join(W, 'text', 'dbs_npc.json'), encoding='utf-8')):
        if x.get('ctx') == 'NPC name':
            en_name, ja_name = x['en'].strip(), (ja.get(x['id']) or '').strip()
            if ja_name and ja_name != en_name and all(0x20 <= ord(c) < 0x7f for c in en_name):
                out.add((ja_name, en_name))
    return sorted(out)


def lit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append('\\' + ch)
        elif 0x20 <= o < 0x7f:
            out.append(ch)
        else:
            out.append('\\u%04x' % o)
    return 'L"' + ''.join(out) + '"'


def main():
    j2e, e2j = build()
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write('/* generated by tools/kwtable.py: keyword tables (Japanese term <-> English keywords) */\n')
        f.write('static const struct { const WCHAR *ja, *en; } g_kw_j2e[] = {\n')
        for t in sorted(j2e):
            f.write('    { %s, %s },\n' % (lit(t), lit('/'.join(j2e[t]))))
        f.write('};\nstatic const struct { const WCHAR *en, *ja; } g_kw_e2j[] = {\n')
        for k in sorted(e2j):
            f.write('    { %s, %s },\n' % (lit(k), lit(e2j[k])))
        f.write('};\n')
        # level triggers named "_<NPC name>" start that NPC's script; the game builds the name from the
        # (translated) NPC.DBS name, so the hook needs the English one back
        f.write('static const struct { const WCHAR *ja; const char *en; } g_npc_name[] = {\n')
        for ja_name, en_name in npc_names():
            f.write('    { %s, %s },\n' % (lit(ja_name), lit(en_name)[1:]))
        f.write('};\n')
    multi = sum(1 for v in j2e.values() if len(v) > 1)
    print('%s: %d Japanese terms (%d with several keywords), %d topic names' % (OUT, len(j2e), multi, len(e2j)))
    if '-v' in sys.argv:
        for t in sorted(j2e, key=lambda t: -len(j2e[t]))[:15]:
            print('  ', t, j2e[t])
        print('   longest:', sorted(e2j.values(), key=len)[-5:])


if __name__ == '__main__':
    main()
